using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using SCUMMexplorer.Core.Discovery;

// Usage: GlossaryCheck <english game folder> <spanish game folder> <output .md>
// Checks every glossary entry against the English data, using the Spanish release the table was written for as the reference.
// Method (no entry is judged by its name): the same code unit (global script, room entry, room local script, object verb)
// is compared across the editions by the shape of its instructions (operation names), and a variable, bit or sound
// is followed by the code units that mention it. Spanish bits from 0xD63 on are numbered 1 lower than in English.
var en = Load(args[0]);
var es = Load(args[1]);
var shift = LoomStoryEvents.FirstBitFor(new GameFolderScanner().Scan(args[0])) - LoomStoryEvents.FirstBit;
var glossary = JsonSerializer.Deserialize<GlossaryFile>(File.ReadAllText("src/SCUMMexplorer.Core/Loom/Text/loom-glossary.json"),
    new JsonSerializerOptions { PropertyNameCaseInsensitive = true })!;
var sb = new StringBuilder();
sb.AppendLine("# Glossary check against the English LOOM EGA data");
sb.AppendLine();
sb.AppendLine($"Generated by `.verification/GlossaryCheck` (English `{args[0]}`, reference `{args[1]}`; bit shift {shift}). Verdicts: **same** (the same code units use the thing in the same way), **moved** (used, with differences listed), **absent** (no English code unit uses it), **n/a** (no code evidence to compare: engine variables).");
sb.AppendLine();

static string Sig(Unit? u) => u is null ? "(missing)" : string.Join(" ", u.Ops.Select(i => i.Operation));
static double Similarity(Unit? a, Unit? b)
{
    if (a is null || b is null) return 0;
    var x = a.Ops.Select(i => i.Operation).ToArray();
    var y = b.Ops.Select(i => i.Operation).ToArray();
    var d = new int[x.Length + 1, y.Length + 1];
    for (var i = 0; i <= x.Length; i++) d[i, 0] = i;
    for (var j = 0; j <= y.Length; j++) d[0, j] = j;
    for (var i = 1; i <= x.Length; i++)
        for (var j = 1; j <= y.Length; j++)
            d[i, j] = Math.Min(Math.Min(d[i - 1, j] + 1, d[i, j - 1] + 1), d[i - 1, j - 1] + (x[i - 1] == y[j - 1] ? 0 : 1));
    return 1.0 - (double)d[x.Length, y.Length] / Math.Max(1, Math.Max(x.Length, y.Length));
}
static HashSet<string> Mentions(Dictionary<string, Unit> units, string token) =>
    units.Where(p => p.Value.Ops.Any(i => i.Operands.Contains(token, StringComparison.Ordinal))).Select(p => p.Key).ToHashSet();
static HashSet<string> SoundUnits(Dictionary<string, Unit> units, int sound) =>
    units.Where(p => p.Value.Ops.Any(i => i.Operation == "startSound" && (i.Operands == $"0x{sound:X2}" || i.Operands.StartsWith($"0x{sound:X2},")))).Select(p => p.Key).ToHashSet();
static string Names(IEnumerable<string> set)
{
    var l = set.OrderBy(x => x, StringComparer.Ordinal).ToList();
    return l.Count == 0 ? "none" : string.Join(", ", l.Take(8)) + (l.Count > 8 ? $" (+{l.Count - 8})" : "");
}
static int Num(string key) => key.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? Convert.ToInt32(key[2..], 16) : int.Parse(key);

var rows = new List<(string Kind, string Key, string Name, string Evidence, string Verdict, string Detail)>();
foreach (var e in glossary.Entries)
{
    string verdict, detail;
    switch (e.Kind)
    {
        case "script":
        {
            var label = $"Script {Num(e.Key):000}";
            en.Units.TryGetValue(label, out var ue);
            es.Units.TryGetValue(label, out var us);
            var s = Similarity(us, ue);
            verdict = ue is null ? "absent" : Sig(ue) == Sig(us) ? "same" : s >= 0.85 ? "same (near)" : "moved";
            detail = $"{us?.Ops.Count ?? 0} instructions in the reference, {ue?.Ops.Count ?? 0} in English, operation-sequence similarity {s:P0}";
            break;
        }
        case "var":
        {
            var token = $"var[0x{Num(e.Key):X3}]";
            var a = Mentions(es.Units, token);
            var b = Mentions(en.Units, token);
            if (b.Count == 0 && a.Count == 0) { verdict = "n/a"; detail = "no code unit mentions it in either edition (engine-side variable)"; break; }
            verdict = b.SetEquals(a) ? "same" : b.Count == 0 ? "absent" : "moved";
            detail = $"mentioned by {a.Count} units in the reference, {b.Count} in English" + (b.SetEquals(a) ? "" : $"; only reference: {Names(a.Except(b))}; only English: {Names(b.Except(a))}");
            break;
        }
        case "bit":
        {
            var v = Num(e.Key);
            var enBit = v >= 0xD63 ? v + shift : v;
            if (v == 0xD62 && shift != 0)
            {
                verdict = "absent";
                detail = $"the Spanish bit has no English counterpart (reference: {Mentions(es.Units, "bit[0xD62]").Count} units); English units mentioning bit[0xD62]: {Names(Mentions(en.Units, "bit[0xD62]"))}";
                break;
            }
            var a = Mentions(es.Units, $"bit[0x{v:X3}]");
            var b = Mentions(en.Units, $"bit[0x{enBit:X3}]");
            verdict = b.SetEquals(a) ? "same" : b.Count == 0 ? "absent" : "moved";
            detail = $"English bit 0x{enBit:X3}: {b.Count} units vs {a.Count} in the reference" + (b.SetEquals(a) ? "" : $"; only reference: {Names(a.Except(b))}; only English: {Names(b.Except(a))}");
            break;
        }
        case "sound":
        {
            var v = Num(e.Key);
            var a = SoundUnits(es.Units, v);
            var b = SoundUnits(en.Units, v);
            verdict = b.SetEquals(a) ? "same" : b.Count == 0 ? "absent" : "moved";
            detail = $"startSound {v} in {b.Count} English units vs {a.Count} in the reference: {Names(b)}";
            break;
        }
        case "room":
        {
            var r = Num(e.Key);
            var inEn = en.Rooms.Contains(r);
            en.Units.TryGetValue($"Room {r:00} entry", out var ue);
            es.Units.TryGetValue($"Room {r:00} entry", out var us);
            var s = Similarity(us, ue);
            verdict = !inEn ? "absent" : s >= 0.85 ? "same" : "moved";
            detail = $"room present in English: {inEn}; entry script similarity {s:P0}; objects {en.ObjectCounts.GetValueOrDefault(r)} English vs {es.ObjectCounts.GetValueOrDefault(r)} reference";
            break;
        }
        default:
            verdict = "n/a";
            detail = "see the actor section below";
            break;
    }
    rows.Add((e.Kind, e.Key + (e.Scope is null ? "" : " [" + e.Scope + "]"), e.Name, e.Evidence, verdict, detail));
}

foreach (var group in rows.GroupBy(r => r.Kind))
{
    sb.AppendLine($"## {group.Key}s");
    sb.AppendLine();
    sb.AppendLine("| Key | Name | Evidence | English | Detail |");
    sb.AppendLine("|---|---|---|---|---|");
    foreach (var r in group) sb.AppendLine($"| {r.Key} | {r.Name} | {r.Evidence} | {r.Verdict} | {r.Detail.Replace("|", "/")} |");
    sb.AppendLine();
}
sb.AppendLine("## Summary");
sb.AppendLine();
foreach (var g in rows.GroupBy(r => r.Verdict).OrderBy(g => g.Key))
    sb.AppendLine($"- {g.Key}: {g.Count()} ({string.Join(", ", g.GroupBy(x => x.Kind).Select(k => $"{k.Count()} {k.Key}"))})");

sb.AppendLine();
sb.AppendLine("## Actors: who speaks in the scenes the glossary cites");
sb.AppendLine();
foreach (var label in new[] { "Script 046", "Script 086", "Script 087", "Script 098", "Script 091", "Script 093", "Script 105", "Room 09 local 221", "Room 09 local 217" })
    foreach (var (name, data) in new[] { ("English", en), ("reference", es) })
    {
        if (!data.Units.TryGetValue(label, out var u)) { sb.AppendLine($"- {label} ({name}): missing"); continue; }
        var lines = u.Ops.Where(i => i.Operation == "print" && i.Operands.Contains("text,"))
            .Select(i => i.Operands.Split(',')[0] + ":" + Regex.Match(i.Operands, "text, \"([^\"]{0,40})").Groups[1].Value).Take(40);
        sb.AppendLine($"- {label} ({name}): {string.Join(" | ", lines)}");
    }
// Story flags (LoomEgaStateFlags): the bits the English code sets from the first story bit on, and which catalog scene names each.
{
    var enGame = new GameFolderScanner().Scan(args[0]);
    var esGame = new GameFolderScanner().Scan(args[1]);
    var enEvents = LoomStoryEvents.Read(enGame);
    var esEvents = LoomStoryEvents.Read(esGame);
    using var catalogStream = File.OpenRead("src/SCUMMexplorer.App/loom-replays.json");
    using var catalog = JsonDocument.Parse(catalogStream);
    var recipes = catalog.RootElement.GetProperty("replays").EnumerateArray()
        .Select(r => (Title: r.GetProperty("title").GetString()!, Room: r.GetProperty("room").GetInt32(), Obj: r.GetProperty("objectId").GetInt32(), Verb: r.GetProperty("verb").GetInt32(),
            Scripts: r.GetProperty("scriptIds").EnumerateArray().Select(x => x.GetInt32()).ToArray(), HasSteps: r.TryGetProperty("steps", out var st) && st.ValueKind == JsonValueKind.Array)).ToList();
    string? Title(LoomStateSource setter)
    {
        if (setter.ObjectId is int o && setter.VerbId is int v) return recipes.FirstOrDefault(r => !r.HasSteps && r.Room == setter.Room && r.Obj == o && r.Verb == v).Title;
        if (setter.Where.StartsWith("Script ", StringComparison.Ordinal) && int.TryParse(setter.Where.AsSpan(7, 3), out var script)) return recipes.FirstOrDefault(r => r.Scripts.Contains(script)).Title;
        return null;
    }
    sb.AppendLine();
    sb.AppendLine("## Story flags (LoomEgaStateFlags) on the English data");
    sb.AppendLine();
    var named = enEvents.Count(e => e.Scenes.Any(x => Title(x) is not null));
    sb.AppendLine($"English: {enEvents.Count} story bits are set by the game's code (first story bit 0x{LoomStoryEvents.FirstBitFor(enGame):X3}); {named} of them are named by a scene of the English catalog, {enEvents.Count - named} stay unnamed (labelled by the setter's script). The Spanish release has {esEvents.Count} (first 0x{LoomStoryEvents.FirstBitFor(esGame):X3}). Each flag's label is the scene title of its setter in the catalog, so a label is as good as the catalog entry's own evidence (the setter is decoded; a scene being the only setter is not claimed).");
    sb.AppendLine();
    sb.AppendLine("| Bit | Setters | Label (catalog scene) | Spanish bit with the same setter labels |");
    sb.AppendLine("|---|---|---|---|");
    foreach (var e in enEvents)
    {
        var titles = e.Scenes.Select(Title).Where(t => t is not null).Distinct().Take(2).ToList();
        var esBit = esEvents.FirstOrDefault(x => x.Bit == e.Bit + 1);
        var esTitles = esBit is null ? new List<string?>() : esBit.Scenes.Select(Title).Where(t => t is not null).Distinct().Take(2).ToList();
        sb.AppendLine($"| {e.Key} | {e.Setters.Count} ({string.Join("; ", e.Setters.Select(x => x.Where.Split(" +")[0]).Distinct().Take(3))}) | {(titles.Count == 0 ? "(unnamed)" : string.Join(" / ", titles))} | {(esBit is null ? "none" : $"{esBit.Key}: {(esTitles.Count == 0 ? "(unnamed)" : string.Join(" / ", esTitles))}")} |");
    }
}
File.WriteAllText(args[2], sb.ToString());
Console.WriteLine($"{rows.Count} entries checked -> {args[2]}");

static Data Load(string folder)
{
    var game = new GameFolderScanner().Scan(folder);
    var scanner = new LoomSceneStateScanner(game);
    var units = new Dictionary<string, Unit>();
    scanner.VisitCodeUnits((script, room, obj, verb, label) => { if (script is not null) units[label] = new Unit(script.Instructions.ToList()); });
    var rooms = game.Rooms.Where(r => r.ResourceId.HasValue).Select(r => r.ResourceId!.Value).ToHashSet();
    var counts = new Dictionary<int, int>();
    foreach (var room in game.Rooms.Where(r => r.ResourceId.HasValue))
        counts[room.ResourceId!.Value] = new ScummRoomObjectDirectory().Decode(File.ReadAllBytes(room.FilePath)).Count;
    return new Data(units, rooms, counts);
}

record Unit(List<ScummScriptInstruction> Ops);
record Data(Dictionary<string, Unit> Units, HashSet<int> Rooms, Dictionary<int, int> ObjectCounts);
record GlossaryRow(string Kind, string Key, string Name, string Evidence, string? Source, string? Scope = null);
record GlossaryFile(List<GlossaryRow> Entries);
