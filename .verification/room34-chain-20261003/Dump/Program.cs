using SCUMMexplorer.Core.Discovery;
using SCUMMexplorer.Core.Formats;
using SCUMMexplorer.Core.Rendering;
var game = new GameFolderScanner().Scan(args[0]);
var res = game.Rooms.Single(r => r.ResourceId == 35);
var recs = new LoomRoomObjectDirectory().Decode(File.ReadAllBytes(res.FilePath));
foreach (var o in recs) Console.WriteLine($"obj {o.Id} x{o.X} y{o.Y} w{o.Width} h{o.Height} walk {o.WalkX},{o.WalkY}");
var dialect = ScummScriptDialects.For(game.Id);
var reader = new LoomScriptReader(dialect);
var gc = new LflIndexReader().ReadDeclaredScriptCount(Path.Combine(args[0], "00.LFL"));
foreach (var i in reader.DecodeRoomLocalScript(res, 204, gc).Instructions) if (i.Offset>=0x7F0 || i.Offset<0x60) Console.WriteLine($"{i.Offset:X4} {i.Operation} {i.Operands}");
